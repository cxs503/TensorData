#!/usr/bin/env python3
"""Render the human-readable asset card for a registered model.

The card is generated from the registry manifest + eval card, so every number in
``docs/models/<model_id>.md`` is traceable to a file whose sha256 is registered —
no hand-copied metrics, no drift between documentation and asset.

Usage::

    python scripts/render_model_card.py --registry models \
        --model dtmb5415-lumped-surrogate --out docs/models/dtmb5415-lumped-surrogate.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from tensordata.modelreg import ModelRegistry, sha256_file  # noqa: E402


def fmt(value) -> str:
    if isinstance(value, float):
        if value != value:  # NaN
            return "n/a"
        if abs(value) >= 1000 or (value != 0 and abs(value) < 1e-3):
            return f"{value:.3e}"
        return f"{value:.3f}"
    return str(value)


def render(registry: ModelRegistry, model_id: str, version: str | None = None) -> str:
    manifest = registry.load_manifest(model_id, version)
    model_dir = registry.model_dir(manifest["model_id"], manifest["version"])
    card_rel = next(a["path"] for a in manifest["artifacts"] if a["role"] == "eval_card")
    card = json.loads((model_dir / card_rel).read_text())
    weights = next(a for a in manifest["artifacts"] if a["role"] == "weights")
    report = registry.verify(manifest["model_id"], manifest["version"])
    metrics = manifest["evaluation"]["metrics"]
    baseline = manifest["evaluation"].get("baseline", {})
    ridge = baseline.get("r2", {})
    split = manifest["training_data"]["split"]

    lines = [
        f"# Model asset card — `{manifest['model_id']}@{manifest['version']}`",
        "",
        f"*{manifest.get('display_name', '')}*",
        "",
        "Generated by `scripts/render_model_card.py` from the registered manifest and eval card "
        "(no hand-copied numbers).",
        "",
        "## Identity and bindings",
        "",
        "| field | value |",
        "|---|---|",
        f"| model_id / version | `{manifest['model_id']}` / `{manifest['version']}` |",
        f"| manifest sha256 | `{manifest['manifest_sha256']}` |",
        f"| weights | `{weights['path']}` · {weights['bytes']} B · {weights.get('format')} · "
        f"{weights.get('framework')} |",
        f"| weights sha256 | `{weights['sha256']}` |",
        f"| training-data fingerprint | `{manifest['training_data']['fingerprint']}` |",
        f"| verification | {'PASS' if report['ok'] else 'FAIL'} "
        f"({len(report['checks'])} checks recomputed) |",
        f"| registered by | {manifest['provenance']['created_by']} |",
        f"| created | {manifest.get('created_utc', 'n/a')} |",
        "",
        "## Task and IO contract",
        "",
        f"- task type: `{manifest['task']['task_type']}` — {manifest['task']['objective']}",
        f"- inputs: `{manifest['io_contract']['inputs'][0]['name']}` "
        f"shape {manifest['io_contract']['inputs'][0]['shape']} "
        f"({manifest['io_contract']['inputs'][0].get('units', '')})",
        f"- outputs: `{manifest['io_contract']['outputs'][0]['name']}` "
        f"shape {manifest['io_contract']['outputs'][0]['shape']}",
        f"- loader: `{manifest['io_contract']['loader']['kind']}` "
        f"layers {manifest['io_contract']['loader'].get('layers')} "
        f"activation {manifest['io_contract']['loader'].get('activation')}",
        "- target columns: " + ", ".join("`" + t["name"] + "`" for t in manifest["task"]["targets"]),
        "",
        "## Training data",
        "",
        "| dataset | version | source | archive sha256 | fingerprint |",
        "|---|---|---|---|---|",
    ]
    for ds in manifest["training_data"]["datasets"]:
        lines.append(f"| `{ds['dataset_ref']}` | `{ds['dataset_version']}` | {ds.get('source_uri', '')} "
                     f"| `{(ds.get('artifact_sha256') or '')[:16]}` | `{ds['fingerprint'][:19]}` |")
    lines += [
        "",
        f"- split: {split['scheme']}, seed {split['seed']}, "
        f"train {split['n_train']} / val {split.get('n_val')} / test {split['n_test']}",
        f"- table: `{manifest['training_data']['fingerprint_recipe']['table_path']}` "
        f"(arrays {', '.join(manifest['training_data']['fingerprint_recipe']['arrays'])})",
        "",
        "## Held-out error table",
        "",
        f"Protocol: {manifest['evaluation']['protocol']}",
        "",
        "| target | R² | ridge R² (same split) | RMSE | MAE | median \\|rel err\\| % | "
        "p95 \\|rel err\\| % | max \\|rel err\\| % |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, m in metrics.items():
        lines.append(
            f"| `{name}` | {fmt(m['r2'])} | {fmt(ridge.get(name))} | {fmt(m['rmse'])} | "
            f"{fmt(m['mae'])} | {fmt(m['median_abs_rel_err_pct'])} | "
            f"{fmt(m['p95_abs_rel_err_pct'])} | {fmt(m['max_abs_rel_err_pct'])} |")
    summary = card.get("summary", {})
    lines += [
        "",
        f"- targets with R² > 0.9: "
        f"{sum(1 for m in metrics.values() if m['r2'] > 0.9)}/{len(metrics)}; "
        f"targets improving on the ridge baseline: "
        f"{sum(1 for k, m in metrics.items() if ridge.get(k) is not None and m['r2'] > ridge[k])}"
        f"/{len(metrics)}",
        f"- median target R² {fmt(summary.get('median_target_r2'))}; "
        f"min target R² {fmt(summary.get('min_target_r2'))}; "
        f"median p95 |rel err| {fmt(summary.get('median_p95_abs_rel_err_pct'))}%",
        f"- relative errors are computed on rows with |y_true| ≥ "
        f"{metrics[list(metrics)[0]]['mape_rel_floor']} × max|y_true| of that column "
        "(near-zero rows excluded and counted in the eval card)",
        "",
        "## Applicability domain",
        "",
        f"{manifest['applicability_domain']['description']}",
        "",
        f"- bounds: `{json.dumps(manifest['applicability_domain']['bounds'])}` "
        f"(policy: `{manifest['applicability_domain']['out_of_domain_policy']}`)",
    ]
    for caveat in manifest["applicability_domain"]["caveats"]:
        lines.append(f"- caveat: {caveat}")
    lines += [
        "",
        "## Reproduce",
        "",
        "```bash",
        manifest["provenance"]["repro_cmd"],
        "```",
        "",
        "```bash",
        f"python -m tensordata.modelreg.cli verify {manifest['model_id']}@{manifest['version']}",
        f"python -m tensordata.modelreg.cli predict {manifest['model_id']} --input rows.json",
        "```",
        "",
        "## Rights",
        "",
        f"- software/weights: {manifest['rights']['license']}; "
        f"training data: {manifest['rights'].get('data_license')}",
        f"- {manifest['rights'].get('redistribution', '')}",
        "",
        f"*eval card artifact sha256: `{sha256_file(model_dir / card_rel)}`*",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--registry", default=str(REPO / "models"))
    parser.add_argument("--model", required=True)
    parser.add_argument("--version", default=None)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    text = render(ModelRegistry(args.registry), args.model, args.version)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())